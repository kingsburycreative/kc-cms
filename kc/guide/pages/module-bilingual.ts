export const body = `<p>If your site is in English and French, every page and post has two versions. The French version is linked to the English one by file name, so the site knows which two belong together.</p>
<h2>Add a post in both languages</h2>
<ol>
  <li>Open <strong>Blog posts (English)</strong> in the menu and choose <strong>Add an entry</strong>.</li>
  <li>Fill in the title, description, date, picture and text. Choose <strong>Save</strong>.</li>
  <li>Open <strong>Blog posts (French)</strong> and choose <strong>Add an entry</strong>.</li>
  <li>In <strong>English post</strong>, search for the English title and pick it.</li>
  <li>Write the French title, description and text. Choose <strong>Save</strong>.</li>
</ol>
<p class="picture-marker">[picture: the French post form with the English post picker open and one title chosen]</p>
<p>The French post takes its file name from the English one. That is the link. Do not rename either file afterwards.</p>
<h2>One French version per English post</h2>
<p>Each English post can have only one French version. If you pick an English post that already has one, the CMS refuses to save. Open the existing French post and edit that instead.</p>
<h2>Change an existing pair</h2>
<p>Edit each language on its own. Changing the English title does not change the French one, so update both when the meaning changes.</p>
<h2>Pages with two versions</h2>
<p>Pages such as Contact are listed twice, once for English and once for French. Open each one and edit it. They have the same boxes, so the two versions stay easy to compare.</p>
<p class="picture-marker">[picture: the menu showing the English and French versions of the Contact page side by side]</p>`;
