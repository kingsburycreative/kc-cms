export const body = `<p>Some parts of your site are lists, such as posts, products or team members. Each item in a list is an entry, and each entry usually gets its own page on the site.</p>
<h2>Add an entry</h2>
<ol>
  <li>Choose the list in the menu on the left.</li>
  <li>Choose <strong>Add an entry</strong> at the top right.</li>
  <li>Fill in the boxes. A box marked Required has to be filled in before the entry will save.</li>
  <li>Choose <strong>Save</strong>.</li>
</ol>
<p class="picture-marker">[picture: a new blank entry, with its boxes and the Save button at the top right]</p>
<p>If something is missing or in the wrong format, the box turns red and a message under it says what to fix. Nothing is saved until every red box is fixed.</p>
<h2>Change an entry later</h2>
<p>Open the list, choose the entry's title, make your change and save.</p>
<h2>Remove an entry</h2>
<ol>
  <li>Open the entry.</li>
  <li>Choose the three dots at the top right, then <strong>Delete</strong>, and confirm.</li>
</ol>
<p class="picture-marker">[picture: an entry with the three-dot menu open, showing Rename and Delete]</p>
<p>Deleting an entry also takes its page off your website, about a minute after you confirm. Any picture or file you attached stays in <strong>Media</strong>. To remove that too, see <a href="core-photos-and-files.html">Photos and files</a>.</p>
<p>Avoid <strong>Rename</strong> on anything already on your site. It changes the page's web address, so links people have saved or shared stop working. To change a title, edit the Title box and leave the name alone.</p>
<p>If you delete something by accident, email us and we can bring it back. See <a href="core-getting-help.html">Getting help</a>.</p>`;
